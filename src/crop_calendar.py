def _config_from_api(data: dict[str, Any]) -> CropConfig:
    """Build a CropConfig from the JSON payload sent by the SPA."""
    name    = data.get("name", "myCrop")
    title   = data.get("title", name)
    preset  = data.get("preset", "grain")
    crop    = CropConfig(name=name, title=title, preset=preset)
    crop.apply_preset()

    calendar_raw = data.get("calendar", [])
    crop.calendar = [
        CalendarEntry(
            zone=e["zone"],
            planting_months=e.get("planting_months", []),
            growing_months=e.get("growing_months", []),
            harvesting_months=e.get("harvesting_months", []),
        )
        for e in calendar_raw
    ]
    return crop


