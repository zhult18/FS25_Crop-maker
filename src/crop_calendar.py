def _cell_class(month: int, entry: CalendarEntry) -> str:
    if month in entry.harvesting_months:
        return "harvest"
    if month in entry.growing_months:
        return "grow"
    if month in entry.planting_months:
        return "plant"
    return "idle"


def _build_export_table(entry: CalendarEntry) -> str:
    header = "".join(f"<th>{a}</th>" for a in MONTH_ABBR)
    cells = "".join(
        '<td class="{cls}">{lbl}</td>'.format(
            cls=_cell_class(m, entry),
            lbl=("P" if m in entry.planting_months
                 else "G" if m in entry.growing_months
                 else "H" if m in entry.harvesting_months
                 else "·"),
        )
        for m in range(1, 13)
    )
    return (
        "<table>"
        f"<tr><th>Zone</th>{header}</tr>"
        f'<tr><td class="zone-label">{entry.zone.capitalize()}</td>{cells}</tr>'
        "</table>"
    )


def generate_calendar_html(crop: CropConfig, output_dir: str | Path) -> Path:
    """Generate a standalone HTML calendar for *crop* and write it to *output_dir*.

    Returns the path to the written file.
    """
    tables = (
        "\n".join(_build_export_table(e) for e in crop.calendar)
        if crop.calendar
        else "<p>No calendar data defined.</p>"
    )
    html = (
        '<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">'
        f"<title>FS25 Crop Calendar – {crop.name}</title>{_EXPORT_CSS}</head><body>"
        "<h1>FS25 Crop Calendar</h1>"
        f'<p class="subtitle">Crop: <strong>{crop.title}</strong>'
        f" &nbsp;|&nbsp; Preset: {crop.preset}</p>"
        '<div class="legend">'
        '<div class="legend-item"><div class="swatch plant-sw"></div> Planting</div>'
        '<div class="legend-item"><div class="swatch grow-sw"></div> Growing</div>'
        '<div class="legend-item"><div class="swatch harvest-sw"></div> Harvesting</div>'
        '<div class="legend-item"><div class="swatch idle-sw"></div> Idle</div>'
        "</div>"
        f"{tables}"
        "<footer>Generated by FS25 Crop Maker &mdash; "
        "https://github.com/zhult18/FS25_Crop-maker</footer>"
        "</body></html>"
    )
    out = ensure_dir(output_dir)
    dest = out / f"{crop.name}_calendar.html"
    dest.write_text(html, encoding="utf-8")
    return dest


